\set ON_ERROR_STOP on

CREATE ROLE primary_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD 'primary_app_ci';
CREATE ROLE primary_migrator WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD 'primary_migrator_ci';
CREATE ROLE demo_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD 'demo_app_ci';
CREATE ROLE demo_migrator WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD 'demo_migrator_ci';

CREATE DATABASE project_desk_primary OWNER primary_migrator;
CREATE DATABASE project_desk_demo OWNER demo_migrator;

REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
REVOKE ALL ON DATABASE project_desk_primary FROM PUBLIC;
REVOKE ALL ON DATABASE project_desk_demo FROM PUBLIC;
GRANT CONNECT ON DATABASE project_desk_primary TO primary_app, primary_migrator;
GRANT CONNECT ON DATABASE project_desk_demo TO demo_app, demo_migrator;

\connect project_desk_primary

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO primary_migrator;
GRANT USAGE ON SCHEMA public TO primary_app;

CREATE SCHEMA drizzle AUTHORIZATION primary_migrator;
REVOKE ALL ON SCHEMA drizzle FROM PUBLIC;
GRANT USAGE ON SCHEMA drizzle TO primary_app;

ALTER DEFAULT PRIVILEGES FOR ROLE primary_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO primary_app;
ALTER DEFAULT PRIVILEGES FOR ROLE primary_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO primary_app;
ALTER DEFAULT PRIVILEGES FOR ROLE primary_migrator IN SCHEMA drizzle
  GRANT SELECT ON TABLES TO primary_app;

\connect project_desk_demo

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO demo_migrator;
GRANT USAGE ON SCHEMA public TO demo_app;

CREATE SCHEMA drizzle AUTHORIZATION demo_migrator;
REVOKE ALL ON SCHEMA drizzle FROM PUBLIC;
GRANT USAGE ON SCHEMA drizzle TO demo_app;

ALTER DEFAULT PRIVILEGES FOR ROLE demo_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO demo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE demo_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO demo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE demo_migrator IN SCHEMA drizzle
  GRANT SELECT ON TABLES TO demo_app;
